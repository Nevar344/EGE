#1.Работа идет с двоичной записью (bin).
#2.Главное условие: "в середину дописывается 1".
#3.Вставка зависит от четности длины строки (количество цифр).
for n in range(1, 100):  # менять: 100 на больше, если ответов нет
    b = bin(n)[2:]  # не трогать
    if len(b) % 2 == 0:  # шаг 2а: если количество цифр чётное
        # делим строку пополам и вставляем '1' между ними
        b = b[:len(b) // 2] + '1' + b[len(b) // 2:]  # менять: '1' на другую цифру, если просят в условии
    # если нечётное (шаг 2б) — запись не изменяется, поэтому else не нужен
    r = int(b, 2)  # не трогать
    if r <= 26:  # менять: число и знак (<=26, >50 и т.д.) из вопроса
        print(n, r)  # пишем в ответ МАКСИМАЛЬНОЕ n из выведенного списка