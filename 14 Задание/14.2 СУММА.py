#Определите сумму числовых значений цифр в 27-ричной записи числа, заданного выражением:
# 2*729**2014 + 2*243**2016 - 2*81**2018 + 2*27**2020 - 2*9**2022 - 2024
x = 2*729**2014 + 2*243**2016 - 2*81**2018 + 2*27**2020 - 2*9**2022 - 2024
k = 0
while x > 0:
    n = x % 27
    k += n
    x = x//27
print(k)
