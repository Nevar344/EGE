# 6. ФОРМУЛА ПИКА — подсчёт точек внутри любой фигуры
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# S = I + B/2 - 1
#
# S — площадь фигуры в квадратных клетках
# I — точки строго ВНУТРИ (то, что ищем)
# B — точки строго НА ГРАНИЦЕ
#
# Ищем I: I = S - B/2 + 1
#
# Как найти B (граничные точки):
#   Для каждого горизонтального/вертикального отрезка длиной L → B += L
#   (не дублируй угловые точки)
#
# Как найти S:
#   Разбей фигуру на прямоугольники.
#   S каждого прямоугольника = ширина × высота (в клетках).
#   Сложи все S, вычти пересечения если есть.

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 7. МИНИМАЛЬНОЕ N ДЛЯ ЗАМКНУТОЙ ЛОМАНОЙ
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# N = 360 / НОД(360, угол_поворота)
#
from math import gcd
def min_N_zamknutoy(ugol):
    return 360 // gcd(360, ugol)

# Примеры:
# min_N_zamknutoy(50) = 36
