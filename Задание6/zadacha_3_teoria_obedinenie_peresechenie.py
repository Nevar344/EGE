# ─── ПЕРИМЕТР ОБЪЕДИНЕНИЯ ФИГУР ───────────────────────────────
#
# Когда две фигуры соединяют в одну (объединение):
#   Периметр объединения = периметр большой фигуры
#                        + стороны малой фигуры, которые СНАРУЖИ большой
#                        - стороны малой фигуры, которые совпали с большой
#
# ПРОЩЕ ГОВОРЯ:
#   Рисуем обе фигуры. Смотрим на внешний контур объединённой фигуры.
#   Считаем только те стороны, которые образуют ВНЕШНЮЮ границу.
#   Общие (совпавшие) стороны в периметр НЕ входят.
#
# Пример: два квадрата 3×3 стоят рядом, одна сторона общая.
#   Периметр каждого = 12
#   Периметр объединения = 12 + 12 - 2×3 = 18  (вычитаем общую сторону дважды)

# ─── ПЕРИМЕТР ПЕРЕСЕЧЕНИЯ ФИГУР ───────────────────────────────
#
# Пересечение — это область, которая принадлежит ОБЕИМ фигурам одновременно.
#   Периметр пересечения = периметр той части, где фигуры накладываются.
#
# Нужно найти, какую фигуру образует «перекрытие», и посчитать её периметр.
# Обычно это прямоугольник или квадрат.

# ─── ТОЧКИ В ОБЪЕДИНЕНИИ ФИГУР ────────────────────────────────
#
# Считаем ВСЕ целые точки, которые лежат строго ВНУТРИ хотя бы одной фигуры.
# Точки, которые лежат в обеих фигурах — считаем ОДИН раз (не дважды!).
# Точки на границах — НЕ считаем.
#
# Формула: |A ∪ B| = |A| + |B| - |A ∩ B|
#   где |A| — точки внутри первой фигуры
#       |B| — точки внутри второй фигуры
#       |A ∩ B| — точки, которые внутри ОБЕИХ фигур одновременно

# ─── ТОЧКИ В ПЕРЕСЕЧЕНИИ ФИГУР ────────────────────────────────
#
# Считаем только те точки, которые лежат строго ВНУТРИ ОБЕИХ фигур.
# То есть точка должна быть внутри первой И внутри второй фигуры.
# Точки на границах — НЕ считаем.
#
# Формула: |A ∩ B| = точки строго внутри перекрывающейся области

# ─── КРИТИЧЕСКИ ВАЖНОЕ ПРАВИЛО: ДЛИНА ≠ КОЛИЧЕСТВО ТОЧЕК ─────
#
# Если черепаха прошла ВПЕРЁД 13 клеток:
#   Длина отрезка = 13
#   Целых точек на отрезке = 14  (0, 1, 2, 3, ..., 13 — включая оба конца)
#
# Но! Если считаем точки ВНУТРИ прямоугольника (не на границе):
#   Прямоугольник от (0,0) до (5,3) → внутри точки: x=1,2,3,4 и y=1,2
#   Количество = 4 × 2 = 8
#   (не 5×3=15, потому что граничные точки не берём)
#
# ФОРМУЛА для подсчёта внутренних точек прямоугольника (a × b клеток):
#   Внутренних точек = (a - 1) × (b - 1)


# ─── ПРАКТИЧЕСКИЙ ПРИМЕР ──────────────────────────────────────
#
# Задача: два прямоугольника 10×6 и 8×4, пересекаются на 3×2 клетки.
# Найти точки в объединении.
#
# Точки внутри первого:  (10-1) × (6-1) = 9 × 5 = 45
# Точки внутри второго:  (8-1) × (4-1)  = 7 × 3 = 21
# Точки в пересечении:   (3-1) × (2-1)  = 2 × 1 = 2
#
# Точки в объединении = 45 + 21 - 2 = 64
