# ╔══════════════════════════════════════════════════════════════╗
# ║  ЗАДАЧА 6 — Найти минимальное N для замкнутой ломаной        ║
# ╠══════════════════════════════════════════════════════════════╣
# ║  УСЛОВИЕ: Найдите минимальное значение N, при котором        ║
# ║  черепаха оставит след в виде замкнутой ломаной линии.       ║
# ║  ОТВЕТ: 36                                                   ║
# ╚══════════════════════════════════════════════════════════════╝

# ─── ЧТО ДЕЛАЕТ ЧЕРЕПАХА ─────────────────────────────────────
# Цикл range(N): каждую итерацию:
#   fd(10k)  → идёт вперёд 10 клеток
#   rt(50)   → поворачивает вправо на 50°
#
# После каждой итерации черепаха повернулась на 50° вправо.
# После N итераций суммарный поворот = N × 50°.
#
# Для замкнутой ломаной нужно ДВА условия:
#   1. Черепаха вернулась в ту же ТОЧКУ.
#   2. Черепаха смотрит в то же НАПРАВЛЕНИЕ.
#
# Условие 2 выполняется когда суммарный поворот кратен 360°:
#   N × 50° = 360° × M  (где M — целое число)
#   N = 360 × M / 50 = 36M / 5
#
# Минимальное целое N при минимальном целом M:
#   M = 5  →  N = 36 × 5 / 5 = 36
#
# Проверка: 36 × 50° = 1800° = 5 × 360° ✓ — 5 полных оборотов.
# ─────────────────────────────────────────────────────────────

from turtle import *

screensize(2000, 2000)
tracer(0)
k = 20
left(90)

for n in range(36):    # при N=36 фигура впервые замыкается
    fd(10 * k)
    rt(50)             # поворот на 50° вправо каждый шаг

up()
mainloop()

# ─── ОБЩАЯ ФОРМУЛА ДЛЯ НАХОЖДЕНИЯ МИНИМАЛЬНОГО N ────────────
#
# Угол поворота = A градусов.
# Ломаная замкнётся, когда N × A кратно 360°.
#
# Минимальное N = 360 / НОД(360, A)
#
# где НОД — наибольший общий делитель.
#
# Примеры:
#   A = 50°:  НОД(360, 50) = 10  →  N = 360 / 10 = 36  ✓
#   A = 90°:  НОД(360, 90) = 90  →  N = 360 / 90 = 4   (квадрат)
#   A = 72°:  НОД(360, 72) = 72  →  N = 360 / 72 = 5   (пятиугольник)
#   A = 60°:  НОД(360, 60) = 60  →  N = 360 / 60 = 6   (шестиугольник)
#   A = 120°: НОД(360, 120) = 120 → N = 360 / 120 = 3  (треугольник)
#   A = 45°:  НОД(360, 45) = 45  →  N = 360 / 45 = 8   (восьмиугольник)
#
# ЕСЛИ УГОЛ НЕ ЦЕЛЫЙ — переводи в дробь.
# Пример: A = 40°: НОД(360, 40) = 40  → N = 9.
#
# ЕСЛИ УГОЛ > 180° — вычти из 360°: rt(250) = поворот на 110° влево.
# Для формулы всегда используй наименьший угол: min(A, 360-A).
# Хотя для формулы НОД(360, A) — не важно, оба дадут правильное N.
#
# ─── СПОСОБ ПОДБОРА (как в оригинале) ────────────────────────
#
# Просто подставляй разные N в range() и запускай программу.
# Смотри, при каком минимальном N линия замыкается.
# НО! Это медленно на экзамене. Лучше использовать формулу выше.
#
# ─── КОД ДЛЯ ПРОВЕРКИ (вычисляет N программно) ──────────────

from math import gcd

A = 50            # угол поворота в градусах
N = 360 // gcd(360, A)
print(f"Угол = {A}°, минимальное N = {N}")
# Вывод: Угол = 50°, минимальное N = 36
