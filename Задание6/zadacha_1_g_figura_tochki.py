# ─── ЧТО РИСУЕТ ЧЕРЕПАХА ──────────────────────────────────────
# Черепаха рисует Г-образный (ступенчатый) замкнутый контур.
# Цикл range(3) повторяет 3 раза:
#   вперёд 27k → вправо 90° → вперёд 12k → вправо 90°
# Итого 6 отрезков — получается трёхступенчатая Г-фигура.
#
# Затем карандаш поднимается, черепаха перемещается на 4k вперёд
# и 6k вправо — это СТАРТ второй фигуры внутри.
# Второй цикл range(3) рисует большой прямоугольник 83k × 77k
# (тоже Г-образно, 3 раза: вперёд 83k → вправо 90° → вперёд 77k → вправо 90°).
#
# Красные точки — визуальная сетка с шагом k для подсчёта.
# ──────────────────────────────────────────────────────────────

from turtle import *

screensize(2000, 2000)
tracer(0)          # убирает анимацию, рисует мгновенно
k = 20             # масштаб: 1 клетка = 20 пикселей

left(90)           # черепаха смотрит вверх

# --- Внутренняя (малая) Г-фигура ---
for i in range(3):
    forward(27 * k)    # вверх 27 клеток
    right(90)          # смотрим вправо
    forward(12 * k)    # вправо 12 клеток
    right(90)          # смотрим вниз

# --- Переход к началу внешней (большой) фигуры ---
up()               # поднять карандаш — идём без рисования
forward(4 * k)     # вниз 4 клетки (смотрим вниз после цикла)
right(90)          # смотрим влево
forward(6 * k)     # влево 6 клеток
left(90)           # смотрим вниз
down()             # опустить карандаш — снова рисуем

# --- Внешняя (большая) Г-фигура ---
for u in range(3):
    forward(83 * k)    # вниз 83 клетки
    right(90)          # смотрим вправо
    forward(77 * k)    # вправо 77 клеток
    right(90)          # смотрим вверх

# --- Сетка красных точек для визуального подсчёта ---
up()
for x in range(-50, 50):
    for y in range(-50, 50):
        goto(x * k, y * k)
        dot(3, "red")

mainloop()

