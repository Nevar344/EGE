# 2. Посчитай, сколько итераций нужно, чтобы суммарный поворот
#    стал кратен 360° И черепаха вернулась на старт.
#    Это число назови P (период фигуры).
# 3. Ответ = N // P
#    (N — количество итераций в range)
#
# Пример: угол 120°, fd одинаковые.
#   3 × 120° = 360° → P = 3
#   range(151) → 151 // 3 = 50 проходов
#
# Пример: угол 90°, fd одинаковые.
#   4 × 90° = 360° → P = 4
#   range(20) → 20 // 4 = 5 проходов
