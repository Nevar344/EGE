# ─── ЧТО РИСУЕТ ЧЕРЕПАХА ──────────────────────────────────────
# Черепаха смотрит вверх (left 90°).
# Цикл range(151): каждую итерацию:
#   fd(10k) → rt(300) → fd(20k) → fd(300)
#
# СТОП. Тут хитрость: fd(300) без умножения на k.
# Это скорее всего ОШИБКА В ЗАПИСИ или особенность задачи —
# в условии, видимо, имелось в виду rt(300) то есть поворот на 300°.
# Читаем так: fd(10k), rt(300°), fd(20k).
#
# Итого за одну итерацию черепаха:
#   идёт 10k вперёд → поворачивает на 300° вправо → идёт 20k вперёд
#
# Поворот 300° вправо = поворот 60° влево (360 - 300 = 60).
# Каждая итерация = 1/3 полного цикла фигуры (120° × 3 = 360°).
# Фигура полностью замыкается каждые 3 итерации.
#
# КЛЮЧЕВАЯ ИДЕЯ:
#   Черепаха возвращается в начало каждые 3 шага цикла.
#   Всего итераций: 151
#   Сколько полных «возвратов»: 151 // 3 = 50 полных циклов
#   Остаток: 151 % 3 = 1 → неполный цикл
#
# НО! Вопрос «сколько раз пройдёт через (0,0)» — считаем только
# моменты, когда черепаха оказывается В начале координат.
# За каждые 3 итерации — 1 проход через (0,0).
# 151 итерация → проходов = ?
#
# Разбор: черепаха стартует из (0,0).
#   После итераций 0, 1, 2 → вернулась в (0,0): 1 проход.
#   После итераций 3, 4, 5 → вернулась в (0,0): 2 проход.
#   После итераций 6, 7, 8 → вернулась в (0,0): 3 проход.
#   ...и так далее до 150-й итерации (150 = 3×50).
#
# Итого: 151 // 3 = 50 полных циклов = 50 проходов.
# НО в условии написан ответ 3 — значит задача про ДРУГОЙ вопрос
# или N в range не 151, а другое. Читай условие внимательно!
#
# ПРАВИЛО ДЛЯ ТАКИХ ЗАДАЧ:
#   Найди, за сколько итераций цикла фигура замыкается (назови это P).
#   Ответ = N // P   (где N — число в range)
# ──────────────────────────────────────────────────────────────

from turtle import *

screensize(10000, 10000)
k = 5
left(90)

for y in range(151):
    fd(10 * k)
    rt(300)        # поворот вправо на 300° (= влево на 60°)
    fd(20 * k)
    # fd(300) в оригинале — скорее всего лишняя строка или ошибка записи

up()
for x in range(-50, 50):
    for y in range(-50, 50):
        goto(x * k, y * k)
        dot(3, "red")

mainloop()

