# Шаг 1: Запусти и посмотри фигуру (или разберись вручную).
# Шаг 2: Определи, замкнута ли линия.
#         7 × 120° = 840° → остаток 840 % 360 = 120° ≠ 0 → НЕ замкнута.
# Шаг 3: Если линия не замкнута — «область» не образована,
#         точек внутри = 0. Либо в задании имеется в виду
#         визуально ограниченная область (тогда считаем по рисунку).
# Шаг 4: Считаем точки строго ВНУТРИ контура, точки на линии — нет.
#
# ФОРМУЛА ЗАМКНУТОСТИ:
#   Фигура замкнётся когда: (N × угол) кратно 360°
#   То есть: (N × угол) % 360 == 0
#
