# ─── ЧТО РИСУЕТ ЧЕРЕПАХА ──────────────────────────────────────
# Черепаха повёрнута вверх (left 90°).
# Цикл range(7): 7 раз — вперёд 10k, поворот вправо 120°.
#
# Угол 120° при 7 итерациях:
#   7 × 120° = 840° = 2 × 360° + 120° — не кратно 360°!
#   Это значит фигура НЕ замкнется идеально за 7 шагов.
#   Получится незамкнутая ломаная из 7 отрезков (звездообразная).
#
# Для правильного замкнутого многоугольника нужно:
#   угол = 360° / N  (для правильного N-угольника)
#   или угол = 360° × P / N  (для звезды, где P — «через сколько вершин»)
#
# Красные точки — визуальная сетка для подсчёта.
# ──────────────────────────────────────────────────────────────

from turtle import *

screensize(2000, 2000)
tracer(0)
left(90)       # смотрим вверх
k = 20

for i in range(7):
    forward(10 * k)    # вперёд 10 клеток
    right(120)         # поворот вправо 120°

up()
for x in range(-50, 50):
    for y in range(-50, 50):
        goto(x * k, y * k)
        dot(3, "red")

mainloop()

