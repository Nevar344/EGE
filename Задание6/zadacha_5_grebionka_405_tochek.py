# ─── ЧТО РИСУЕТ ЧЕРЕПАХА ──────────────────────────────────────
# Черепаха смотрит вверх (left 90°), масштаб k = 20.
# Цикл range(13): 13 раз повторяет:
#   fd(10k) → rt(90°) → fd(10k) → rt(90°) → fd(30k) → rt(90°)
#
# Разберём одну итерацию (черепаха смотрит вверх):
#   fd(10k)  → вверх 10 клеток
#   rt(90°)  → смотрим вправо
#   fd(10k)  → вправо 10 клеток
#   rt(90°)  → смотрим вниз
#   fd(30k)  → вниз 30 клеток
#   rt(90°)  → смотрим влево... стоп, смотрим ВПРАВО уже был разворот
#
# ВАЖНО: Суммарный поворот за итерацию = 3 × 90° = 270° вправо.
# 270° вправо = 90° влево. Значит следующая итерация черепаха
# уже смотрит на 90° левее предыдущей. Через 4 итерации = 360° = полный оборот.
#
# В итоге рисуется гребёнка — фигура с зубчиками.
# Форма похожа на расчёску: основание внизу, зубцы вверх.
#
# РАЗМЕРЫ (в клетках, делим пиксели на k=20):
#   Шаг вперёд: 10 клеток
#   Шаг вправо: 10 клеток
#   Шаг вниз:   30 клеток
#   Итераций:   13
# ──────────────────────────────────────────────────────────────

from turtle import *

screensize(2000, 2000)
tracer(0)
k = 20
left(90)

for i in range(13):
    fd(10 * k)     # вверх 10 клеток
    rt(90)         # смотрим вправо
    fd(10 * k)     # вправо 10 клеток
    rt(90)         # смотрим вниз
    fd(30 * k)     # вниз 30 клеток
    rt(90)         # смотрим влево (или в зависимости от итерации)

up()
for x in range(-50, 50):
    for y in range(-50, 50):
        goto(x * k, y * k)
        dot(3, "red")

mainloop()

