# Нарисуй фигуру на бумаге в клетку и разбей на прямоугольники.
# Для каждого прямоугольника (a × b клеток) внутренние точки:
#   = (a - 1) × (b - 1)
#
# Потом сложи точки всех прямоугольников, вычти пересечения.
#
# Альтернатива — метод подсчёта по формуле Пика:
#   S = I + B/2 - 1
#   где S — площадь (в клетках²)
#       I — точки строго внутри (то, что ищем)
#       B — точки на границе
#
#   Отсюда: I = S - B/2 + 1
#
# ФОРМУЛА ПИКА — самый надёжный способ для задания 6!
#
# Шаги применения формулы Пика:
#   1. Найди площадь S фигуры (разбей на прямоугольники, сложи).
#   2. Посчитай точки на границе B (суммируй длины всех сторон,
#      каждый отрезок длиной L даёт L точек на границе,
#      угловые точки не дублируются).
#   3. Применяй формулу: I = S - B/2 + 1
#
